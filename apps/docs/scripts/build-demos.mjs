// Regenerates components/demos/index.ts from the files in components/demos.
// Run with `pnpm --filter docs demos` after adding or renaming a demo.
import { readdirSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const names = readdirSync(resolve(root, "components/demos"))
  .filter((file) => file.endsWith(".tsx"))
  .map((file) => file.replace(/\.tsx$/, ""))
  .sort()

const pascal = (name) =>
  name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")

const lines = [
  "// GENERATED by scripts/build-demos.mjs. Do not edit by hand.",
  "// Static imports so every demo is bundled and rendered on its docs page.",
  "",
]
for (const name of names) lines.push(`import ${pascal(name)} from './${name}';`)
lines.push("", "export const demos = {")
for (const name of names) lines.push(`  '${name}': ${pascal(name)},`)
lines.push("} as const", "", "export type DemoName = keyof typeof demos", "")

writeFileSync(resolve(root, "components/demos/index.ts"), lines.join("\n"))
console.log(`demos: ${names.length} -> components/demos/index.ts`)
